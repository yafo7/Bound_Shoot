
CREATE TABLE IF NOT EXISTS schema_migrations(version INTEGER PRIMARY KEY);
CREATE TABLE IF NOT EXISTS users(
 id TEXT PRIMARY KEY, username TEXT NOT NULL UNIQUE COLLATE NOCASE, display_name TEXT NOT NULL,
 password_hash TEXT NOT NULL, created_at INTEGER NOT NULL, games INTEGER NOT NULL DEFAULT 0,
 wins INTEGER NOT NULL DEFAULT 0, kills INTEGER NOT NULL DEFAULT 0, deaths INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS user_cosmetics(user_id TEXT PRIMARY KEY REFERENCES users(id), skin INTEGER NOT NULL DEFAULT 0 CHECK(skin BETWEEN 0 AND 3));
CREATE TABLE IF NOT EXISTS auth_sessions(
 id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), refresh_hash TEXT NOT NULL UNIQUE,
 expires_at INTEGER NOT NULL, revoked INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS rooms(
 id TEXT PRIMARY KEY, code TEXT NOT NULL UNIQUE, host_id TEXT NOT NULL REFERENCES users(id),
 size INTEGER NOT NULL DEFAULT 2, map_id TEXT NOT NULL DEFAULT 'Arena_01',
 status TEXT NOT NULL DEFAULT 'Waiting', match_id TEXT);
CREATE TABLE IF NOT EXISTS room_members(
 user_id TEXT PRIMARY KEY REFERENCES users(id), room_id TEXT NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
 team INTEGER NOT NULL, seat INTEGER NOT NULL, ready INTEGER NOT NULL DEFAULT 0,
 last_seen INTEGER NOT NULL, UNIQUE(room_id,team,seat));
CREATE TABLE IF NOT EXISTS matches(
 id TEXT PRIMARY KEY, room_id TEXT NOT NULL, map_id TEXT NOT NULL, port INTEGER NOT NULL,
 secret_hash TEXT NOT NULL, status TEXT NOT NULL, created_at INTEGER NOT NULL,
 heartbeat INTEGER NOT NULL, ended_at INTEGER, winner INTEGER, duration REAL, result TEXT);
CREATE UNIQUE INDEX IF NOT EXISTS active_ports ON matches(port) WHERE status IN ('Starting','Ready','Playing');
CREATE TABLE IF NOT EXISTS match_players(
 match_id TEXT NOT NULL REFERENCES matches(id), user_id TEXT NOT NULL REFERENCES users(id),
 username TEXT NOT NULL, skin INTEGER NOT NULL, team INTEGER NOT NULL, seat INTEGER NOT NULL,
 kills INTEGER NOT NULL DEFAULT 0, deaths INTEGER NOT NULL DEFAULT 0, damage INTEGER NOT NULL DEFAULT 0,
 PRIMARY KEY(match_id,user_id), UNIQUE(match_id,team,seat));
CREATE TABLE IF NOT EXISTS match_tickets(
 hash TEXT PRIMARY KEY, match_id TEXT NOT NULL REFERENCES matches(id), user_id TEXT NOT NULL,
 expires_at INTEGER NOT NULL, used INTEGER NOT NULL DEFAULT 0);
